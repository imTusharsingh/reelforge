import { describe, expect, it } from "vitest";
import { ProviderError } from "@reelforge/ai-providers";
import {
  applicableKinds,
  assertVideoCapability,
  isCompletePackage,
  validateGeneratedMedia,
} from "./scene-media.validation.js";
import { SCENE_MEDIA_SCHEMA_VERSION, type SceneMediaPackage } from "./scene-media.types.js";

const scene = {
  id: "one",
  startSeconds: 0,
  durationSeconds: 4,
  characterRefs: [],
  dialogue: "  ",
  narration: "",
  visualDescription: "A street",
  camera: "wide",
  audioCues: [],
};

describe("scene media validation", () => {
  it("requests narration only when the scene has narration text", () => {
    expect(
      applicableKinds(scene, { image: true, video: false, narration: true, dialogue: true }),
    ).toEqual(["IMAGE"]);
    expect(
      applicableKinds(
        { ...scene, narration: "Hello", dialogue: "Line" },
        { image: true, video: true, narration: true, dialogue: true },
      ),
    ).toEqual(["IMAGE", "VIDEO", "NARRATION", "DIALOGUE"]);
  });

  it("rejects motion when the provider capability is not video", () => {
    expect(() =>
      assertVideoCapability(
        {
          providerId: "fixture",
          capabilityId: "image",
          kind: "image",
          input: ["text"],
          output: ["image"],
          supportsReferenceImages: false,
          asynchronous: false,
          polling: false,
          regions: [],
          costModel: { currency: "USD", unit: "request", amount: 1 },
        },
        4,
        "correlation",
      ),
    ).toThrow(ProviderError);
  });

  it("rejects empty and mismatched generated bytes", () => {
    expect(() => validateGeneratedMedia("IMAGE", "image/png", new Uint8Array())).toThrow(/empty/i);
    expect(() =>
      validateGeneratedMedia("IMAGE", "image/png", Uint8Array.from([0, 0, 0, 0])),
    ).toThrow(/does not match/i);
    expect(() =>
      validateGeneratedMedia(
        "VIDEO",
        "image/png",
        Uint8Array.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
      ),
    ).toThrow(/not acceptable/i);
  });

  it("requires every bound scene output to carry real media before export", () => {
    const pkg: SceneMediaPackage = {
      schemaVersion: SCENE_MEDIA_SCHEMA_VERSION,
      jobId: "job",
      workspaceId: "workspace",
      scriptId: "script",
      scriptRevision: 1,
      channelId: null,
      status: "SUCCEEDED",
      idempotencyKey: "key",
      configSnapshotId: "config",
      promptSnapshotId: "prompt",
      requestedOutputs: { image: true, video: false, narration: false, dialogue: false },
      scenes: [
        {
          sceneId: "one",
          ordinal: 0,
          sceneVersion: 1,
          status: "SUCCEEDED",
          idempotencyKey: "scene",
          sourceRefs: {},
          outputs: [
            {
              kind: "IMAGE",
              status: "SUCCEEDED",
              assetId: null,
              assetVersion: null,
              mediaType: "image/png",
              byteSize: 0,
              checksumSha256: null,
              providerJobId: "job",
              providerAssetId: "asset",
              correlationId: null,
              reusedFromOutputId: null,
              errorCode: null,
              errorMessage: null,
            },
          ],
        },
      ],
    };
    expect(isCompletePackage(pkg)).toBe(false);
  });
});
